#!/usr/bin/env python3
"""Generates Sources/ProcXRay/Sys/SyscallArgNames.swift: argument names for BSD syscalls and Mach traps.

Sources (Apple's published xnu): bsd/kern/syscalls.master (C prototypes, by number), osfmk/mach/mach_traps.h
(PAD_ARG_(type, name) structs, one per trap) and osfmk/kern/syscall_sw.c (the Mach trap table, by number).
    tools/gen-syscall-argnames.py <syscalls.master> <mach_traps.h> <syscall_sw.c> > Sources/ProcXRay/Sys/SyscallArgNames.swift
Fetch them with:
    curl -O https://raw.githubusercontent.com/apple-oss-distributions/xnu/main/bsd/kern/syscalls.master
    curl -O https://raw.githubusercontent.com/apple-oss-distributions/xnu/main/osfmk/mach/mach_traps.h
    curl -O https://raw.githubusercontent.com/apple-oss-distributions/xnu/main/osfmk/kern/syscall_sw.c
"""
import re
import sys


def bsd(path):
    names, numbers = {}, {}
    proto = re.compile(r'^\d+\s+\S+\s+\S+\s+\{\s*(.*?)\s*\}')
    for line in open(path):
        m = proto.match(line)
        if not m:
            continue
        f = re.match(r'.*?\b(\w+)\s*\((.*)\)', m.group(1))
        if not f:
            continue
        name, args = f.group(1), f.group(2).strip()
        if name in ('nosys', 'enosys'):
            continue
        numbers.setdefault(int(line.split()[0]), name)
        if args in ('', 'void'):
            names.setdefault(name, [])
            continue
        out = []
        for a in args.split(','):
            ident = re.findall(r'(\w+)\s*(?:\[\w*\])?\s*$', a.strip())
            out.append(ident[0] if ident else '')
        names.setdefault(name, out)
    return names, numbers


def trap_numbers(path):
    out = {}
    for m in re.finditer(r'/\*\s*(\d+)\s*\*/\s*MACH_TRAP\(\s*(\w+)', open(path).read()):
        if m.group(2) != 'kern_invalid':
            out[int(m.group(1))] = m.group(2)
    return out


def mach(path):
    names = {}
    text = open(path).read()
    for m in re.finditer(r'struct\s+(\w+)_args\s*\{(.*?)\};', text, re.S):
        fields = re.findall(r'PAD_ARG_\w*\(\s*[^,]+,\s*(\w+)\s*\)', m.group(2))
        name = m.group(1)
        if name.startswith('_kernelrpc_'):
            name = name[len('_kernelrpc_'):]
        names.setdefault(name, fields)
    return names


def swift(table):
    return ',\n'.join(f'        "{k}": [{", ".join(chr(34) + a + chr(34) for a in v)}]' for k, v in sorted(table.items()))


(b, bnum), m, tnum = bsd(sys.argv[1]), mach(sys.argv[2]), trap_numbers(sys.argv[3])


def numbers(table):
    return ',\n'.join(f'        {k}: "{v}"' for k, v in sorted(table.items()))

print('''// Generated by tools/gen-syscall-argnames.py from xnu's bsd/kern/syscalls.master, osfmk/mach/mach_traps.h and
// osfmk/kern/syscall_sw.c.
// Do not edit by hand.

/// Argument names by call, as xnu declares them.
enum SyscallArgNames {
    static let bsd: [String: [String]] = [
''' + swift(b) + '''
    ]

    static let mach: [String: [String]] = [
''' + swift(m) + '''
    ]

    /// Names by number, for calls the system's trace.codes doesn't name (it lags the kernel: trap 63 showed as
    /// kern_invalid_63).
    static let bsdNumbers: [Int: String] = [
''' + numbers(bnum) + '''
    ]
    static let machNumbers: [Int: String] = [
''' + numbers(tnum) + '''
    ]
}''')
